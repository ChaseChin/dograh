"""Rendering the bundled Asterisk gateway's trunk configuration from the DB.

The gateway Asterisk is configured the way an Asterisk is configured: from files
under ``/etc/asterisk``. Those files are the only place a SIP trunk's host and
port can live, so Dograh writes them, and writes them whole — the file is a pure
function of the configurations that currently exist. That is what makes create,
edit, and delete converge on the same output without a delete hook: a
configuration that no longer exists simply stops being rendered.

The API container and the gateway share the directory as a volume. Nothing here
talks to Asterisk; reloading is the gateway's own job, because it holds the CLI
and does not need ARI credentials to run ``pjsip reload``.
"""

from __future__ import annotations

import os
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Dict, List, Sequence

from loguru import logger

# Where the shared volume is mounted. The image sets it; the default matches so
# a developer running the API outside a container gets the same layout.
DEFAULT_CONF_DIR = "/etc/asterisk/dograh"
CONF_DIR_ENV = "ASTERISK_CONF_DIR"

PJSIP_FILENAME = "pjsip-dograh.conf"
DIALPLAN_FILENAME = "extensions-dograh.conf"

# Asterisk's own defaults for a trunk that carries voice. Kept here, next to the
# sections that use them, so the whole trunk definition reads in one place.
_ALLOWED_CODECS = "ulaw"


@dataclass(frozen=True)
class GatewayTrunk:
    """One configuration's trunk, as the gateway needs to see it."""

    label: str
    endpoint: str
    host: str
    port: int
    transport: str

    @property
    def dialplan_context(self) -> str:
        return f"{self.endpoint}-in"


def _pjsip_section(trunk: GatewayTrunk) -> str:
    """The endpoint/aor/identify trio for one trunk.

    There is no ``auth`` section: the carrier recognises this server by its
    source IP, which is what "no credentials" means for a SIP trunk. Inbound is
    matched by ``identify`` for the same reason — the peer's address is the
    whole of its identity.

    ``context`` is what routes an inbound call into this configuration's Stasis
    application and nobody else's; without it every trunk would land in the same
    dialplan and one configuration would receive another's calls.

    ``match`` reuses the configured host, which holds when the carrier gives one
    address for both directions — the usual case. Two ways it can be wrong, both
    worth knowing when inbound calls do not arrive: a carrier that signals from
    addresses other than the one it told you to dial, and a hostname that does
    not resolve from this container, where Asterisk drops the whole ``identify``
    and logs it only in its own log.
    """
    return f"""; --- {trunk.label} ---
[{trunk.endpoint}]
type=endpoint
transport=transport-{trunk.transport}
context={trunk.dialplan_context}
disallow=all
allow={_ALLOWED_CODECS}
direct_media=no
rtp_symmetric=yes
force_rport=yes
rewrite_contact=yes
aors={trunk.endpoint}

[{trunk.endpoint}]
type=aor
contact=sip:{trunk.host}:{trunk.port}

[{trunk.endpoint}]
type=identify
endpoint={trunk.endpoint}
match={trunk.host}
"""


def _dialplan_context(trunk: GatewayTrunk) -> str:
    """The dialplan that hands inbound calls on this trunk to Dograh.

    The extension pattern is deliberately open: which workflow answers is
    decided by the called number in Dograh, and a dialplan that tried to
    enumerate the carrier's numbers here would have to be kept in step with
    them. Anything arriving on this trunk belongs to this configuration.

    ``_[+0-9].`` rather than the obvious ``_.``: Asterisk warns on every reload
    that a bare ``_.`` "can have unexpected behavior", and that warning would
    sit in the gateway log beside the real ones. This matches the same numbers —
    a carrier delivers digits, with or without the leading ``+`` that E.164
    writes and most trunks strip.
    """
    return f"""; --- {trunk.label} ---
[{trunk.dialplan_context}]
exten => _[+0-9].,1,NoOp(SIP trunk inbound to ${{EXTEN}})
 same => n,Stasis({trunk.endpoint})
 same => n,Hangup()
"""


def render_gateway_config(trunks: Sequence[GatewayTrunk]) -> Dict[str, str]:
    """Render the two generated files the gateway includes.

    Pure: same trunks in, same text out. The header states where the file came
    from, because the first thing anyone does with a generated config is edit
    it, and the edit is lost on the next reconcile.
    """
    header = (
        "; Generated by Dograh from the active SIP trunk configurations.\n"
        "; Any change made here is overwritten; edit the configuration in\n"
        "; Dograh's telephony settings instead.\n"
    )
    sections = "".join(_pjsip_section(trunk) for trunk in trunks)
    contexts = "".join(_dialplan_context(trunk) for trunk in trunks)
    return {
        PJSIP_FILENAME: f"{header}\n{sections}",
        DIALPLAN_FILENAME: f"{header}\n{contexts}",
    }


def _write_if_changed(path: Path, content: str) -> bool:
    """Write ``content`` to ``path`` unless it is already there.

    Returns whether the file changed, which the caller uses to tell a real
    update from a poll that found nothing to do. Written via a temporary file
    so the gateway's own reader never sees a half-written config.
    """
    try:
        if path.exists() and path.read_text() == content:
            return False
    except OSError as error:
        logger.warning(f"[Asterisk gateway] Could not read {path}: {error}")

    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(content)
    os.replace(temporary, path)
    return True


class AsteriskGatewayReconciler:
    """Keeps the gateway's generated config in step with the stored trunks.

    Idempotent and cheap enough to run on a timer: it re-reads the
    configurations, re-renders, and writes only when the text differs.

    It reconciles every provider that drives an Asterisk, not just the one whose
    trunks it renders. A configuration only becomes a trunk if its credentials
    carry a host — the carriers this deployment connects to — and every other
    Asterisk-driven configuration contributes nothing. That is what keeps a
    customer's own PBX, which is reached at a host Dograh must not write into a
    trunk, out of a file it has no business being in.
    """

    def __init__(
        self,
        provider_names: str | Sequence[str],
        conf_dir: str | Path | None = None,
    ) -> None:
        self.provider_names: List[str] = (
            [provider_names]
            if isinstance(provider_names, str)
            else list(provider_names)
        )
        self.conf_dir = Path(
            conf_dir or os.getenv(CONF_DIR_ENV) or DEFAULT_CONF_DIR
        )

    @property
    def available(self) -> bool:
        """Whether the gateway has prepared the shared directory for writing.

        The compose stack mounts the volume into the api unconditionally, so
        that enabling the bundled gateway later is a matter of starting the
        container and not of editing the api's mounts. The consequence is that
        the directory is present from the api's first second — Docker creates a
        named volume's root owned by root, mode 0755 — while the api writes as
        its own unprivileged user and cannot open a file there. The gateway
        chmods the directory world-writable as it starts, and that is the point
        at which these writes can land.

        So test writability, not existence. Against an installation that never
        started a gateway the directory exists and is not writable, and this
        says so once per poll instead of logging a permission error once a
        minute for the life of the deployment.
        """
        return self.conf_dir.is_dir() and os.access(self.conf_dir, os.W_OK)

    def _trunks_from_rows(self, rows: Sequence[Any]) -> List[GatewayTrunk]:
        trunks: List[GatewayTrunk] = []
        for row in rows:
            credentials: Dict[str, Any] = row.credentials or {}
            host = credentials.get("hostname")
            if not host:
                # Not a trunk-carrying configuration — an Asterisk the customer
                # owns, reached at a host that must never be written here. Its
                # absence from this file is the correct outcome, not a defect.
                continue
            endpoint = credentials.get("stasis_app_name")
            if not endpoint:
                logger.warning(
                    f"[Asterisk gateway] Configuration {row.id} names a trunk "
                    f"host but has no generated endpoint; skipping"
                )
                continue
            trunks.append(
                GatewayTrunk(
                    label=row.name or f"config {row.id}",
                    endpoint=endpoint,
                    host=host,
                    port=int(credentials.get("port") or 5060),
                    transport=(credentials.get("transport") or "udp").lower(),
                )
            )
        return trunks

    async def reconcile(self) -> bool:
        """Re-render the gateway config. Returns whether anything changed."""
        if not self.available:
            return False
        if not self.provider_names:
            return False

        from api.db import db_client

        try:
            rows = await db_client.list_active_telephony_configurations_by_provider(
                self.provider_names
            )
        except Exception as error:
            logger.error(f"[Asterisk gateway] Failed to load configurations: {error}")
            return False

        rendered = render_gateway_config(self._trunks_from_rows(rows))

        changed = False
        for filename, content in rendered.items():
            if _write_if_changed(self.conf_dir / filename, content):
                logger.info(
                    f"[Asterisk gateway] Updated {filename} "
                    f"({len(content)} bytes)"
                )
                changed = True

        return changed