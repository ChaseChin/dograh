#!/bin/bash
#
# Renders Dograh's Asterisk gateway configuration, then hands off to the base
# image's entrypoint so it can do its own job (adapting uid/gid for the mounted
# volume) and start Asterisk.
#
# Two kinds of file live here, and the split is the whole design:
#
#   * Everything in /etc/asterisk is this deployment's — the ARI user the API
#     authenticates as, the transports the carrier's trunks ride, the WebSocket
#     client that carries audio to the API. It comes from environment variables
#     and changes only when the container is recreated.
#
#   * Everything in /etc/asterisk/dograh is written by the API from the trunk
#     configurations stored in the database. This script creates the directory
#     and then leaves those files alone — except to notice when they change and
#     reload Asterisk, which is the part the API cannot do for itself, having no
#     CLI socket into this container.
#
# Nothing here reads the database or talks to the API. The gateway has one job
# on the SIP side, and the API has one job on the other; a failure in either is
# visible on its own side of the line.

set -euo pipefail

CONF_DIR=/etc/asterisk
GENERATED_DIR="$CONF_DIR/dograh"
BASE_ENTRYPOINT=/usr/local/bin/entrypoint.sh

# How often to look for changes in the API-written trunk configuration. Short
# enough that a configuration saved in the UI is live well before anyone can
# finish dialling a test call.
WATCH_INTERVAL_SECONDS="${ASTERISK_WATCH_INTERVAL_SECONDS:-5}"

ARI_USER="${ASTERISK_ARI_USER:-dograh}"
ARI_PASSWORD="${ASTERISK_ARI_PASSWORD:-}"
WS_CLIENT_NAME="${ASTERISK_WS_CLIENT_NAME:-dograh}"
API_WS_URL="${ASTERISK_API_WS_URL:-ws://api:8000/api/v1/telephony/ws/ari}"
SIP_PORT="${ASTERISK_SIP_PORT:-5060}"
SIP_TRANSPORTS="${ASTERISK_SIP_TRANSPORTS:-udp}"
RTP_START="${ASTERISK_RTP_START:-10000}"
RTP_END="${ASTERISK_RTP_END:-10100}"
# The address the carrier sees. Set on any host with a public IP, or calls
# connect and then carry no audio — the classic NAT failure, where signalling
# is fine and the RTP is addressed to a private IP the carrier cannot reach.
EXTERNAL_ADDRESS="${ASTERISK_EXTERNAL_ADDRESS:-}"
# The private range this container lives in, so Asterisk can tell its own
# network from the carrier's without guessing.
LOCAL_NET="${ASTERISK_LOCAL_NET:-}"

log() {
    echo "[dograh-gateway] $*"
}

# Write a file only when its content would change, so a container restart does
# not churn files Asterisk has already loaded.
write_if_changed() {
    local path="$1"
    local content
    content="$(cat)"

    if [ -f "$path" ] && [ "$(cat "$path")" = "$content" ]; then
        return 0
    fi

    printf '%s\n' "$content" > "$path.tmp"
    mv "$path.tmp" "$path"
    log "wrote $path"
}

if [ -z "$ARI_PASSWORD" ]; then
    log "ASTERISK_ARI_PASSWORD is not set — refusing to start."
    log "Dograh authenticates to this gateway over ARI; without a password"
    log "every call fails with an authentication error. Set it in the"
    log "environment file this stack reads, and set the same value for the"
    log "api service."
    exit 1
fi

# --- The directory the API writes trunks into -------------------------------
#
# Created world-writable on purpose. The API writes here as its own unprivileged
# user (uid 999 in the Dograh image) while Asterisk runs as a different one, and
# neither has a way to chown the other's files. What the directory holds is a
# trunk's host, port and codec — the carrier's public settings, and exactly the
# values this integration exists to make non-secret.
install -d -m 0777 "$GENERATED_DIR"
# Explicit, because it is the API's green light rather than a cosmetic mode:
# Docker creates the volume's root owned by root at 0755, and the API treats a
# directory it cannot write to as "no gateway here" and stays quiet. `install -d`
# sets the mode when it creates the directory; this also covers the case where
# the directory already exists because the volume was mounted on a previous run.
chmod 0777 "$GENERATED_DIR"

# Asterisk reads these through a wildcard include. An empty file loads as no
# sections, which is what an installation with no trunks configured should look
# like — as opposed to a missing file, which Asterisk reports as an error on
# every reload.
for name in pjsip-dograh.conf extensions-dograh.conf; do
    if [ ! -f "$GENERATED_DIR/$name" ]; then
        install -m 0666 /dev/null "$GENERATED_DIR/$name"
    fi
done

# --- ARI: the credentials the API drives this gateway with ------------------

write_if_changed "$CONF_DIR/ari.conf" <<EOF
; Generated by the Dograh gateway entrypoint from the environment.
; Any change made here is overwritten on the next container start; change the
; environment instead.

[general]
enabled = yes
pretty = yes

[$ARI_USER]
type = user
read_only = no
password = $ARI_PASSWORD
EOF

write_if_changed "$CONF_DIR/http.conf" <<EOF
; Generated by the Dograh gateway entrypoint. Bound to every interface because
; the API reaches this over the compose network; the port is not published to
; the host.

[general]
enabled = yes
bindaddr = 0.0.0.0
bindport = 8088
EOF

# --- Media: the WebSocket Asterisk opens back to Dograh ---------------------
#
# Dograh asks for an externalMedia channel per call and passes the routing
# parameters through this connection's URI at that moment, so the URI here is a
# base address with no query string.
write_if_changed "$CONF_DIR/websocket_client.conf" <<EOF
; Generated by the Dograh gateway entrypoint.

[$WS_CLIENT_NAME]
type = websocket_client
uri = $API_WS_URL
protocols = media
EOF

# --- Signalling: the transports the carrier's trunks ride -------------------

{
    echo "; Generated by the Dograh gateway entrypoint."
    echo ";"
    echo "; One transport per protocol a trunk may be configured for. The trunk"
    echo "; configurations under dograh/ name these as transport-<protocol>; a"
    echo "; trunk naming one that is not defined here never loads, and Asterisk"
    echo "; says so only in its own log."
    echo
    for protocol in $SIP_TRANSPORTS; do
        echo "[transport-$protocol]"
        echo "type = transport"
        echo "protocol = $protocol"
        echo "bind = 0.0.0.0:$SIP_PORT"
        if [ -n "$EXTERNAL_ADDRESS" ]; then
            # Without these two, Asterisk advertises the container's private
            # address in SDP and the carrier sends audio nowhere.
            echo "external_signaling_address = $EXTERNAL_ADDRESS"
            echo "external_media_address = $EXTERNAL_ADDRESS"
        fi
        if [ -n "$LOCAL_NET" ]; then
            echo "local_net = $LOCAL_NET"
        fi
        echo
    done
    echo "#include dograh/pjsip-dograh.conf"
} | write_if_changed "$CONF_DIR/pjsip.conf"

write_if_changed "$CONF_DIR/rtp.conf" <<EOF
; Generated by the Dograh gateway entrypoint.

[general]
rtpstart = $RTP_START
rtpend = $RTP_END
$(if [ -n "$EXTERNAL_ADDRESS" ]; then echo "externaddr = $EXTERNAL_ADDRESS"; fi)
$(if [ -n "$LOCAL_NET" ]; then echo "localnet = $LOCAL_NET"; fi)
EOF

# --- Dialplan: inbound calls land in the API-written contexts ---------------

write_if_changed "$CONF_DIR/extensions.conf" <<'EOF'
; Generated by the Dograh gateway entrypoint.
;
; Every context that reaches an agent is written by the API, one per trunk
; configuration, under dograh/. This file only declares the globals and pulls
; them in — a hand-written context here would be a route no configuration
; knows about.

[general]
static = yes
writeprotect = yes

#include dograh/extensions-dograh.conf
EOF

# --- Reloading --------------------------------------------------------------
#
# The API rewrites the trunk files whenever the configurations change, but it
# has no CLI socket into this container, so this is where a change becomes a
# reload. Comparing the concatenated content catches every edit without needing
# to track mtimes, and an unchanged poll does nothing at all.

watch_generated_config() {
    local stamp="" current
    while true; do
        sleep "$WATCH_INTERVAL_SECONDS"

        current="$(cat "$GENERATED_DIR"/*.conf 2>/dev/null | md5sum)"
        if [ "$current" = "$stamp" ]; then
            continue
        fi

        # Asterisk is not necessarily up yet, and a reload that fails must not
        # be recorded as done: leaving the stamp unset retries next time round.
        if ! asterisk -rx "core show uptime" >/dev/null 2>&1; then
            continue
        fi

        if asterisk -rx "pjsip reload" >/dev/null 2>&1 \
            && asterisk -rx "dialplan reload" >/dev/null 2>&1; then
            log "reloaded trunk configuration"
            stamp="$current"
        else
            log "reload failed; will retry"
        fi
    done
}

watch_generated_config &

log "starting Asterisk"
exec "$BASE_ENTRYPOINT" "$@"